const originalNodes = [...document.querySelectorAll('[data-t]')];
originalNodes.forEach(node => { translations.ro[node.dataset.t] = node.innerText; });
document.querySelectorAll('[data-aria]').forEach(node => { translations.ro[node.dataset.aria] = node.getAttribute('aria-label'); });
document.querySelectorAll('[data-alt]').forEach(node => { translations.ro[node.dataset.alt] = node.alt; });
translations.ro.title = document.title;
translations.ro.description = document.querySelector('meta[name="description"]').content;

let language = 'ro';
let activeFilter = 'all';
let expanded = false;
let activePhoto = 0;
let galleryOpener = null;
const photos = window.PROJECT_PHOTOS || [];
const gallery = document.getElementById('gallery');
const moreButton = document.getElementById('show-more');
const lightbox = document.getElementById('lightbox');
const lightboxImage = document.getElementById('lightbox-image');
const lightboxCaption = document.getElementById('lightbox-caption');
const translate = key => translations[language][key] || translations.ro[key] || '';
const imageUrl = (photo, thumbnail = false) => `work-${String(photo.id).padStart(2,'0')}${thumbnail ? '-thumb' : ''}.webp`;
const filteredPhotos = () => activeFilter === 'all' ? photos : photos.filter(photo => photo.category === activeFilter);

function setLanguage(next, updateUrl = true) {
  language = next === 'hu' ? 'hu' : 'ro';
  document.documentElement.lang = language;
  document.title = translate('title');
  document.querySelector('meta[name="description"]').content = translate('description');
  document.querySelector('meta[property="og:title"]').content = translate('title');
  document.querySelector('meta[property="og:description"]').content = translate('description');
  document.querySelector('meta[property="og:locale"]').content = language === 'hu' ? 'hu_HU' : 'ro_RO';
  document.querySelector('meta[property="og:locale:alternate"]').content = language === 'hu' ? 'ro_RO' : 'hu_HU';
  originalNodes.forEach(node => {
    const text = translate(node.dataset.t);
    node.replaceChildren(...text.split('\n').flatMap((line,index) => index ? [document.createElement('br'),document.createTextNode(line)] : [document.createTextNode(line)]));
  });
  document.querySelectorAll('[data-aria]').forEach(node => node.setAttribute('aria-label',translate(node.dataset.aria)));
  document.querySelectorAll('[data-alt]').forEach(node => node.alt = translate(node.dataset.alt));
  document.querySelectorAll('[data-lang]').forEach(button => button.setAttribute('aria-pressed',String(button.dataset.lang === language)));
  document.querySelector('.brand').setAttribute('aria-label',`TIBICONSTRUCT BIHOR — ${language === 'hu' ? 'Kezdőlap' : 'Acasă'}`);
  document.querySelectorAll('.whatsapp-link').forEach(link => link.href = `https://wa.me/40755461840?text=${encodeURIComponent(translate('whatsappMessage'))}`);
  if (updateUrl) {
    const url = new URL(window.location.href);
    if (language === 'hu') url.searchParams.set('lang','hu'); else url.searchParams.delete('lang');
    history.replaceState(null,'',url);
  }
  renderGallery();
  if (lightbox.open) updateLightbox();
}

function renderGallery() {
  const filtered = filteredPhotos();
  const shown = expanded ? filtered : filtered.slice(0,8);
  const fragment = document.createDocumentFragment();
  shown.forEach((photo,index) => {
    const figure = document.createElement('figure');
    figure.className = 'gallery-item';
    const button = document.createElement('button');
    button.type = 'button';
    button.setAttribute('aria-label',`${language === 'hu' ? 'Nagyítás' : 'Mărește'}: ${photo[language]}`);
    const img = document.createElement('img');
    img.src = imageUrl(photo,true); img.alt = photo[language]; img.width = photo.width; img.height = photo.height;
    img.loading = 'lazy'; img.decoding = 'async';
    const zoom = document.createElement('span');
    zoom.className = 'zoom-mark'; zoom.setAttribute('aria-hidden','true');
    zoom.innerHTML = '<svg class="icon"><use href="#i-plus"/></svg>';
    button.append(img,zoom);
    button.addEventListener('click',() => openLightbox(index,button));
    const caption = document.createElement('figcaption');
    const title = document.createElement('span'); title.textContent = photo[language];
    const number = document.createElement('span'); number.textContent = String(photo.id).padStart(2,'0');
    caption.append(title,number); figure.append(button,caption); fragment.append(figure);
  });
  gallery.replaceChildren(fragment);
  document.getElementById('photo-count').textContent = language === 'hu' ? `${filtered.length} fénykép` : `${filtered.length} ${filtered.length >= 20 ? 'de ' : ''}fotografii`;
  moreButton.hidden = filtered.length <= 8;
  moreButton.setAttribute('aria-expanded',String(expanded));
  moreButton.setAttribute('aria-controls','gallery');
  moreButton.querySelector('span').textContent = expanded ? translate('showLess') : language === 'hu' ? `Mind a ${filtered.length} fénykép megtekintése` : `Vezi toate cele ${filtered.length} ${filtered.length >= 20 ? 'de ' : ''}fotografii`;
}

function openLightbox(index,opener) {
  activePhoto = index; galleryOpener = opener;
  updateLightbox();
  lightbox.showModal();
  document.body.classList.add('modal-open');
  document.getElementById('lightbox-close').focus();
}
function updateLightbox() {
  const filtered = filteredPhotos();
  const photo = filtered[activePhoto];
  if (!photo) return;
  lightboxImage.src = imageUrl(photo);
  lightboxImage.alt = photo[language];
  lightboxCaption.textContent = photo[language];
  document.getElementById('lightbox-count').textContent = `${String(activePhoto+1).padStart(2,'0')} / ${String(filtered.length).padStart(2,'0')}`;
}
function movePhoto(direction) {
  activePhoto = (activePhoto + direction + filteredPhotos().length) % filteredPhotos().length;
  updateLightbox();
}
document.querySelectorAll('[data-lang]').forEach(button => button.addEventListener('click',() => setLanguage(button.dataset.lang)));
document.querySelectorAll('[data-filter]').forEach(button => button.addEventListener('click',() => {
  activeFilter = button.dataset.filter; expanded = false;
  document.querySelectorAll('[data-filter]').forEach(filter => filter.setAttribute('aria-pressed',String(filter === button)));
  renderGallery();
}));
moreButton.addEventListener('click',() => {
  expanded = !expanded; renderGallery();
  if (!expanded) document.getElementById('lucrari').scrollIntoView({behavior:window.matchMedia('(prefers-reduced-motion: reduce)').matches ? 'instant' : 'smooth'});
});
document.getElementById('lightbox-close').addEventListener('click',() => lightbox.close());
document.getElementById('lightbox-prev').addEventListener('click',() => movePhoto(-1));
document.getElementById('lightbox-next').addEventListener('click',() => movePhoto(1));
lightbox.addEventListener('close',() => {
  document.body.classList.remove('modal-open');
  if (galleryOpener?.isConnected) galleryOpener.focus({preventScroll:true});
});
lightbox.addEventListener('keydown',event => {
  if(event.key === 'ArrowRight') { event.preventDefault(); movePhoto(1); }
  if(event.key === 'ArrowLeft') { event.preventDefault(); movePhoto(-1); }
});
let touchStart = null;
lightboxImage.addEventListener('touchstart',event => { touchStart = event.changedTouches[0].clientX; },{passive:true});
lightboxImage.addEventListener('touchend',event => {
  if(touchStart === null) return;
  const difference = event.changedTouches[0].clientX - touchStart;
  if(Math.abs(difference) > 50) movePhoto(difference > 0 ? -1 : 1);
  touchStart = null;
},{passive:true});
window.addEventListener('popstate',() => setLanguage(new URLSearchParams(window.location.search).get('lang'),false));
setLanguage(new URLSearchParams(window.location.search).get('lang'),false);
